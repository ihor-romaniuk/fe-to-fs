"""Задача 1. Розминка в REPL."""

d = {"a": 1}
items = [("petro", 2), ("olena", 2), ("ivan", 5)]


# 1. bool — підклас int, тому True це буквально 1.
#    isinstance враховує ієрархію типів, тому перевірка на int проходить.
print("1) isinstance(True, int)  ->", isinstance(True, int))          # True
print("   True + True            ->", True + True)                    # 2


# 2. type(x) дає ТОЧНИЙ клас, без нащадків: для True це bool, а bool та int —
#    різні об'єкти класів. Для перевірки типу беремо isinstance, не type(...) is.
print("2) type(True) is int      ->", type(True) is int)              # False
print("   type(True)             ->", type(True))                     # <class 'bool'>


# 3. == питає про вміст, is — чи це той самий об'єкт у пам'яті.
a = [1, 2]
b = [1, 2]
print("3) a == b                 ->", a == b)                         # True
print("   a is b                 ->", a is b)                         # False

# Warning тут не буде: CPython попереджає про `is` лише коли операнд —
# константа (str, int, tuple), а список будується в рантаймі.

# c = a не копіює список, а дає йому друге ім'я.
c = a
c.append(3)
print("   a після c.append(3)    ->", a)                              # [1, 2, 3]

# Пастка: однакові літерали в одному файлі компілятор зводить в один об'єкт,
# тому is на рядках іноді дає True випадково. Правило: is — тільки з None.
s1 = "довгий рядок"
s2 = "довгий рядок"
print("   s1 is s2 (літерали)    ->", s1 is s2)                       # True (!)


# 4. Дефолт обчислюється ОДИН раз — коли Python читає рядок def. Усі виклики
#    без аргументу ділять один список, і append псує його назавжди.
def f(x=[]):
    x.append(1)
    return x


print("4) f() перший раз         ->", f())                            # [1]
print("   f() другий раз         ->", f())                            # [1, 1]
print("   f.__defaults__         ->", f.__defaults__)                 # ([1, 1],)


# Правильно: дефолт None, список створюємо всередині — свіжий на кожен виклик.
def f_ok(x=None):
    x = [] if x is None else x
    x.append(1)
    return x


print("   f_ok(), f_ok()         ->", f_ok(), f_ok())                 # [1] [1]

# На бекенді це критично: функція живе стільки ж, скільки процес, тому такий
# дефолт стає прихованим станом, що тече між запитами різних користувачів.


# 5. Множина (set) — без порядку й без дублікатів. Операції замінюють цикли
#    там, де треба порівняти два набори: права, поля форми, списки id.
print("5) {1,2} & {2,3} перетин  ->", {1, 2} & {2, 3})                # {2}
print("   {1,2} | {2,3} об'єдн.  ->", {1, 2} | {2, 3})                # {1, 2, 3}
print("   {1,2} - {2,3} різниця  ->", {1, 2} - {2, 3})                # {1}


# 6. d[k] — "ключ мусить бути", інакше падіння. d.get(k) — "може й не бути",
#    поверне None. Обирайте свідомо: зламані дані краще ловити гучно й одразу.
try:
    d["k"]
except KeyError as e:
    print("6) d['k']                 -> KeyError:", e)

# repr потрібен, бо REPL не показує None і здається, що нічого не сталося.
print("   d.get('k')             ->", repr(d.get("k")))               # None
print("   d.get('k', 0)          ->", d.get("k", 0))                  # 0


# 7. Неявного приведення типів немає: + для рядка з числом не визначений.
#    Приводимо руками — і саме приведення каже, чого ми хотіли.
try:
    "6" + 6
except TypeError as e:
    print("7) '6' + 6                -> TypeError:", e)

print("   '6' + str(6)           ->", "6" + str(6))                   # '66'
print("   int('6') + 6           ->", int("6") + 6)                   # 12


# 8. key= — функція, за значенням якої сортувати (аналог t => ... у JS).
#    Кортеж у ключі задає пріоритет полів, мінус перевертає порядок чисел:
#    sorted завжди сортує за зростанням, а -5 < -2, тож п'ятірка стає першою.
print("8) за (-кількість, ім'я)  ->", sorted(items, key=lambda t: (-t[1], t[0])))

# sorted стабільний: за однакового ключа порядок лишається вихідним —
# petro перед olena. І він не мутує оригінал, на місці сортує items.sort().
print("   тільки за t[1]         ->", sorted(items, key=lambda t: t[1]))
print("   items не змінився      ->", items)
