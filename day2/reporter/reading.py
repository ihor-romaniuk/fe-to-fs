"""Построкове читання файлу генератором."""

from collections.abc import Iterator


# yield робить функцію генератором, як function* у JS: виклик iter_lines(path)
# лише створює об'єкт-ітератор, а тіло не виконує ні рядка, навіть open().
# Тіло біжить шматками: до наступного yield на кожен next(), тобто на кожен
# крок for. Тому @timed на такій функції показав би ~0 ms: він міряв би
# створення генератора, а не читання файлу.
#
# with усередині генератора тримає файл відкритим, поки його ітерують. Файл
# закривається, коли рядки скінчились, або коли генератор закрили раніше:
# gen.close() (його ж викликає збирач сміття) кидає GeneratorExit у рядок
# yield, і with відпрацьовує свій вихід, як при будь-якому винятку.
def iter_lines(path: str) -> Iterator[str]:
    """Віддати непорожні рядки файлу по одному, без пробілів по краях."""
    with open(path, encoding="utf-8") as f:
        # Файл сам є ітератором рядків і читає їх буфером, а не весь файл одразу.
        for line in f:
            stripped = line.strip()
            if stripped:
                yield stripped
